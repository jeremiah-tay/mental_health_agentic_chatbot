# inner 3-fold search for best lora hyperparameters
def inner_search_lora(model_id, Xarr, yarr, inner_k=3):
    inner = StratifiedKFold(n_splits=inner_k, shuffle=True, random_state=SEED)
    best, best_score = None, -1.0

    for lr in LORA_LRS:
        for rnk in LORA_RANKS:
            for dr in LORA_DROPS:
                f1s = []
                for tr, va in inner.split(Xarr, yarr):
                    Xt, yt = Xarr[tr], yarr[tr]
                    Xv, yv = Xarr[va], yarr[va]

                    tok = get_tokenizer(model_id)
                    tr_enc = tok(list(Xt), truncation=True, padding=True, max_length=256)
                    va_enc = tok(list(Xv), truncation=True, padding=True, max_length=256)
                    tr_ds = SimpleTextDataset(tr_enc, yt.tolist())
                    va_ds = SimpleTextDataset(va_enc, yv.tolist())

                    base = AutoModelForSequenceClassification.from_pretrained(model_id, num_labels=2)
                    lcfg = LoraConfig(
                        r=rnk,
                        lora_alpha=16,
                        lora_dropout=dr,
                        target_modules=["query","value"],
                        bias="none",
                        task_type="SEQ_CLS"
                    )
                    model = get_peft_model(base, lcfg).to(device)

                    args = TrainingArguments(
                        output_dir="/content/tmp",
                        per_device_train_batch_size=16,
                        num_train_epochs=2,
                        learning_rate=lr,
                        eval_strategy="no",
                        save_strategy="no",
                        report_to=[]
                    )

                    trainer = Trainer(model=model, args=args, train_dataset=tr_ds)
                    trainer.train()

                    logits = Trainer(model=model, args=args).predict(va_ds).predictions
                    probs = torch.softmax(torch.tensor(logits), dim=1)[:,1].numpy()
                    th = tune_threshold(yv, probs)
                    f1s.append(f1_score(yv, (probs>=th).astype(int), average="macro"))

                    del trainer, model
                    torch.cuda.empty_cache()

                mean_f1 = float(np.mean(f1s))
                if mean_f1 > best_score:
                    best_score = mean_f1
                    best = {"lr": lr, "rank": rnk, "dropout": dr}

    return best

