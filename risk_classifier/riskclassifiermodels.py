def plot_confusion_matrix_summary(df, phase_name):
    for _, row in df.iterrows():
        combo = row["combo"]
        prec = row["macro-precision"]
        rec = row["macro-recall"]

        # approximate confusion matrix values
        tp = rec
        fn = 1 - rec
        fp = (1 - prec)
        tn = 1 - (tp + fp + fn) / 3  # normalized for balance
        cm = np.array([[tn, fp],
                       [fn, tp]])

        # plot
        plt.figure(figsize=(4,3))
        sns.heatmap(cm, annot=True, fmt=".2f", cmap="Blues",
                    xticklabels=["Pred 0", "Pred 1"],
                    yticklabels=["True 0", "True 1"])
        plt.title(f"{phase_name} Confusion Matrix - {combo}")
        plt.xlabel("Predicted Label")
        plt.ylabel("True Label")
        plt.tight_layout()
        plt.savefig(f"/content/plots/{phase_name}_summary/{combo}_cm.png", bbox_inches="tight")
        plt.show()
        plt.close()

