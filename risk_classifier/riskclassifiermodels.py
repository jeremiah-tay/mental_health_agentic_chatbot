# helper dataset and utilities

class SimpleTextDataset(torch.utils.data.Dataset):
    def __init__(self, encodings, labels):
        self.enc = encodings
        self.labels = labels
    def __len__(self): return len(self.labels)
    def __getitem__(self, i):
        item = {k: torch.tensor(v[i]) for k, v in self.enc.items()}
        item["labels"] = torch.tensor(self.labels[i], dtype=torch.long)
        return item

# toknise
TOKENIZERS = {}
def get_tokenizer(model_id):
    if model_id not in TOKENIZERS:
        TOKENIZERS[model_id] = AutoTokenizer.from_pretrained(model_id, use_fast=True)
    return TOKENIZERS[model_id]

# embeddings
@torch.no_grad()
def get_embeddings(model_id, texts_list):
    tok = get_tokenizer(model_id)
    base = AutoModel.from_pretrained(model_id).to(device).eval()
    vecs = []
    bs = 64
    for i in range(0, len(texts_list), bs):
        chunk = texts_list[i:i+bs]
        enc = tok(chunk, truncation=True, padding=True, max_length=256, return_tensors="pt").to(device)
        out = base(**enc)
        if hasattr(out, "pooler_output") and out.pooler_output is not None:
            v = out.pooler_output
        else:
            v = out.last_hidden_state.mean(dim=1)
        vecs.append(v.detach().cpu().numpy())
    return np.vstack(vecs)

# logreg classifier
def make_logreg(C=1.0):
    return LogisticRegression(
        C=C, solver="saga", max_iter=2000, n_jobs=-1, class_weight="balanced", tol=1e-3
    )

# determine best threshold to use
def tune_threshold(y_true, y_prob):
    p, r, t = precision_recall_curve(y_true, y_prob)
    f1 = 2*p*r/(p+r+1e-9)
    i = int(np.argmax(f1))
    if i >= len(t): return 0.5
    return float(t[i])

# compute 6 macro eval metrics
def compute_metrics(y_true, y_prob, th):
    y_pred = (y_prob >= th).astype(int)
    m = {
        "macro-accuracy":  accuracy_score(y_true, y_pred),
        "macro-F1":        f1_score(y_true, y_pred, average="macro"),
        "macro-recall":    recall_score(y_true, y_pred, average="macro"),
        "macro-precision": precision_score(y_true, y_pred, average="macro"),
        "roc-auc":         roc_auc_score(y_true, y_prob) if len(np.unique(y_true))==2 else np.nan
    }
    cm = confusion_matrix(y_true, y_pred, labels=[0,1])
    return m, cm

# plot and save auc-roc curve
def show_and_save_roc(y_true, y_prob, path, title):
    plt.figure()
    try:
        RocCurveDisplay.from_predictions(y_true, y_prob)
    except:
        plt.text(0.5, 0.5, "roc failed", ha="center")
    plt.title(title); plt.savefig(path, bbox_inches="tight"); plt.show(); plt.close()

# plot and save confusion metrics
def show_and_save_cm(cm, path, title):
    plt.figure()
    plt.imshow(cm, cmap="Blues"); plt.title(title)
    for (i,j),v in np.ndenumerate(cm):
        plt.text(j, i, str(v), ha="center", va="center",
                 color="white" if v > cm.max()/2 else "black")
    plt.xlabel("pred"); plt.ylabel("true")
    plt.tight_layout(); plt.savefig(path, bbox_inches="tight"); plt.show(); plt.close()

